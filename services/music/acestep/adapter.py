"""
Factory-to-ACE-Step parameter mapping.

Artifact persistence is intentionally not handled here. Queue workers must
upload generated bytes through Factory Storage before constructing an
ArtifactReference.
"""
from typing import Any, Dict

from factory_contracts.errors import InvalidRequestError


class ACEStepAdapter:
    @staticmethod
    def map_inputs(task: str, inputs: Dict[str, Any]) -> Dict[str, Any]:
        if task not in {"text_to_music", "lyrics_to_music"}:
            raise InvalidRequestError(
                f"Music task '{task}' is not enabled until source-audio staging is implemented."
            )

        prompt = str(inputs.get("prompt") or "").strip()
        if not prompt:
            raise InvalidRequestError("Music generation requires a non-empty prompt.")

        params: Dict[str, Any] = {
            "prompt": prompt,
            "duration_seconds": inputs.get("duration_seconds", 60),
            "tempo": inputs.get("tempo", inputs.get("bpm", 120)),
            "seed": inputs.get("seed"),
            "audio_format": inputs.get("audio_format", "mp3"),
            "thinking": inputs.get("thinking", False),
        }
        if task == "lyrics_to_music":
            lyrics = str(inputs.get("lyrics") or "").strip()
            if not lyrics:
                raise InvalidRequestError("lyrics_to_music requires non-empty lyrics.")
            params["lyrics"] = lyrics
        return params

    @staticmethod
    def create_artifact_reference(*_args, **_kwargs):
        raise RuntimeError(
            "ArtifactReference must be created only after audio bytes are persisted through Factory Storage."
        )
