"""
Factory-to-ACE-Step parameter mapping and validation.

Artifact persistence is intentionally not handled here. Queue workers must
upload generated bytes through Factory Storage before constructing an
ArtifactReference.
"""
import math
import re
from typing import Any, Dict, Optional, Set

from factory_contracts.errors import (
    ErrorCode,
    InvalidRequestError,
    UnsupportedCapabilityError,
)

# Canonical task aliases for ACE-Step 1.5
BASE_VARIANTS: Set[str] = {"base", "2b_base", "xl_base", "standard", "default"}
TURBO_VARIANTS: Set[str] = {"turbo", "2b_turbo", "sft"}
ALL_VARIANTS: Set[str] = BASE_VARIANTS | TURBO_VARIANTS

# Tasks strictly restricted to base and xl_base variants
SPECIALIZED_BASE_ONLY_TASKS: Set[str] = {"music.extract", "music.lego", "music.complete", "music.extend"}

ALL_SUPPORTED_TASKS: Set[str] = {
    "music.text_to_music",
    "music.lyrics_to_music",
    "music.reference_audio",
    "music.cover",
    "music.repaint",
    "music.extract",
    "music.lego",
    "music.complete",
    "music.extend",
    "music.audio_to_audio",
}

VALID_AUDIO_FORMATS: Set[str] = {"mp3", "wav", "flac"}
KEY_REGEX = re.compile(r"^[A-G][b#]?(?:[ \t]*(?:major|minor|maj|min|m))?$", re.IGNORECASE)
TIME_SIG_REGEX = re.compile(r"^([1-9]|1[0-6])/([1248]|16)$")


class ACEStepAdapter:
    """Validates and maps Factory music requests to ACE-Step native parameters."""

    @classmethod
    def normalize_variant(cls, variant: Optional[str]) -> str:
        norm = str(variant or "").strip().lower()
        if not norm or norm in ("standard", "default"):
            return "base"
        return norm

    @classmethod
    def is_task_supported_for_variant(cls, task: str, variant: Optional[str] = None) -> bool:
        canonical_task = task
        norm_var = cls.normalize_variant(variant)
        if canonical_task not in ALL_SUPPORTED_TASKS:
            return False
        if canonical_task in SPECIALIZED_BASE_ONLY_TASKS:
            return norm_var in BASE_VARIANTS
        return norm_var in ALL_VARIANTS

    @classmethod
    def validate_variant_capability(cls, task: str, variant: Optional[str] = None) -> None:
        canonical_task = task
        norm_var = cls.normalize_variant(variant)

        if canonical_task not in ALL_SUPPORTED_TASKS:
            raise InvalidRequestError(
                f"ACE-Step does not support task '{task}'. "
                f"Supported tasks: {sorted(list(ALL_SUPPORTED_TASKS))}"
            )

        if norm_var not in ALL_VARIANTS:
            raise InvalidRequestError(
                f"Unknown variant '{variant}'. Supported variants: {sorted(list(ALL_VARIANTS))}"
            )

        if canonical_task in SPECIALIZED_BASE_ONLY_TASKS and norm_var in TURBO_VARIANTS:
            raise UnsupportedCapabilityError(
                message=(
                    f"Task '{canonical_task}' is not supported on variant '{norm_var}'. "
                    f"Specialized editing/separation tasks (extract, lego, complete, music_extend) "
                    f"require the 'base' or 'xl_base' checkpoint."
                ),
                details={
                    "task": canonical_task,
                    "variant": norm_var,
                    "error_code": ErrorCode.UNSUPPORTED_CAPABILITY.value,
                },
            )

    @classmethod
    def map_inputs(cls, task: str, inputs: Dict[str, Any]) -> Dict[str, Any]:
        canonical_task = task
        variant = cls.normalize_variant(inputs.get("variant"))

        # 1. Variant and capability enforcement (§7.1)
        cls.validate_variant_capability(canonical_task, variant)

        # 2. Prompt validation
        prompt = str(inputs.get("prompt") or "").strip()
        if not prompt and canonical_task not in {"music.extract", "music.complete"}:
            raise InvalidRequestError(f"Music task '{canonical_task}' requires a non-empty prompt.")

        # Default prompt for extract/complete if empty
        if not prompt:
            if canonical_task == "music.extract":
                stem = str(inputs.get("stem_name") or inputs.get("target_stem") or "vocals").strip()
                prompt = f"extract {stem} stem"
            elif canonical_task == "music.complete":
                prompt = "complete accompaniment"

        # 3. Instrumental and Lyrics mapping (ACE-02, ACE-03, ACE-15)
        instrumental = bool(inputs.get("instrumental", False))
        lyrics = str(inputs.get("lyrics") or "").strip()
        if canonical_task == "music.lyrics_to_music":
            if not lyrics:
                raise InvalidRequestError("lyrics_to_music requires non-empty lyrics.")
        elif instrumental or "[inst]" in prompt.lower() or not lyrics:
            if canonical_task in {"music.text_to_music", "music.cover", "music.complete"}:
                lyrics = "[inst]"

        # 4. Musical controls (ACE-06): BPM / Tempo
        raw_bpm = inputs.get("bpm", inputs.get("tempo", 120))
        try:
            bpm = int(raw_bpm)
        except (ValueError, TypeError) as exc:
            raise InvalidRequestError(f"BPM/tempo must be an integer, got: {raw_bpm}") from exc
        if bpm < 30 or bpm > 300:
            raise InvalidRequestError(f"BPM must be between 30 and 300, got: {bpm}")

        # Musical controls: Key
        key = inputs.get("key")
        if key is not None:
            key_str = str(key).strip()
            if key_str and not KEY_REGEX.match(key_str):
                raise InvalidRequestError(
                    f"Invalid musical key '{key_str}'. Examples of valid keys: 'C', 'C major', 'Am', 'F#m', 'Bb'."
                )
            key = key_str if key_str else None

        # Musical controls: Time signature
        time_signature = inputs.get("time_signature")
        if time_signature is not None:
            ts_str = str(time_signature).strip()
            if ts_str and not TIME_SIG_REGEX.match(ts_str):
                raise InvalidRequestError(
                    f"Invalid time signature '{ts_str}'. Expected format like '4/4', '3/4', '6/8'."
                )
            time_signature = ts_str if ts_str else None

        # Duration validation
        raw_duration = inputs.get("duration_seconds", inputs.get("audio_duration", 60.0))
        try:
            duration_seconds = float(raw_duration)
        except (ValueError, TypeError) as exc:
            raise InvalidRequestError(f"duration_seconds must be a number, got: {raw_duration}") from exc
        if math.isnan(duration_seconds) or duration_seconds <= 0.0 or duration_seconds > 300.0:
            raise InvalidRequestError(
                f"duration_seconds must be between 1.0 and 300.0 seconds, got: {duration_seconds}"
            )

        # 5. Audio format export validation (ACE-18)
        audio_format = str(inputs.get("output_format", inputs.get("audio_format", "mp3"))).strip().lower()
        if audio_format not in VALID_AUDIO_FORMATS:
            raise InvalidRequestError(
                f"Unsupported audio_format '{audio_format}'. Supported formats: {sorted(list(VALID_AUDIO_FORMATS))}"
            )

        # 6. Source Audio validation (ACE-08, ACE-09, ACE-11, ACE-12, ACE-13, ACE-14)
        src_audio = (
            inputs.get("source_audio_asset_id")
            or inputs.get("src_audio_path")
            or inputs.get("source_audio_path")
            or inputs.get("audio_url")
        )
        if canonical_task in {"music.cover", "music.repaint", "music.extract", "music.lego", "music.complete", "music.extend", "music.audio_to_audio"}:
            if not src_audio:
                raise InvalidRequestError(
                    f"Task '{canonical_task}' requires source audio (source_audio_asset_id or source_audio_path)."
                )

        # 7. Reference Audio validation (ACE-07)
        ref_audio = (
            inputs.get("reference_audio_asset_id")
            or inputs.get("reference_audio_path")
            or inputs.get("reference_audio_url")
        )
        if canonical_task == "music.reference_audio" and not ref_audio:
            raise InvalidRequestError(
                "Task 'reference_audio' requires reference audio (reference_audio_asset_id or reference_audio_path)."
            )

        # 8. Cover strength validation (ACE-08)
        raw_strength = inputs.get("audio_cover_strength", inputs.get("cover_strength", 0.8))
        try:
            cover_strength = float(raw_strength)
        except (ValueError, TypeError) as exc:
            raise InvalidRequestError(f"cover_strength must be a float, got: {raw_strength}") from exc
        if math.isnan(cover_strength) or cover_strength < 0.0 or cover_strength > 1.0:
            raise InvalidRequestError(
                f"cover_strength must be between 0.0 and 1.0, got: {cover_strength}"
            )

        # 9. Repainting interval validation (ACE-09)
        repainting_start = inputs.get("repainting_start")
        repainting_end = inputs.get("repainting_end")
        if repainting_start is not None or repainting_end is not None:
            if repainting_start is None or repainting_end is None:
                raise InvalidRequestError("Both 'repainting_start' and 'repainting_end' must be specified for repaint.")
            try:
                r_start = float(repainting_start)
                r_end = float(repainting_end)
            except (ValueError, TypeError) as exc:
                raise InvalidRequestError("repainting_start and repainting_end must be numbers.") from exc
            if math.isnan(r_start) or math.isnan(r_end) or r_start < 0.0 or r_start >= r_end or r_end > duration_seconds:
                raise InvalidRequestError(
                    f"Invalid repaint interval [{r_start}, {r_end}]. "
                    f"Must satisfy 0.0 <= start < end <= duration ({duration_seconds}s)."
                )
            repainting_start = r_start
            repainting_end = r_end

        # 10. LoRA parameter validation (ACE-22)
        lora_path = inputs.get("lora_path") or inputs.get("lora_name")
        lora_weight = inputs.get("lora_weight", 1.0)
        if lora_weight is not None:
            try:
                lora_weight = float(lora_weight)
            except (ValueError, TypeError) as exc:
                raise InvalidRequestError(f"lora_weight must be a float, got: {lora_weight}") from exc
            if math.isnan(lora_weight) or lora_weight < -2.0 or lora_weight > 2.0:
                raise InvalidRequestError(f"lora_weight must be between -2.0 and 2.0, got: {lora_weight}")

        # Assemble normalized parameter dictionary
        params: Dict[str, Any] = {
            "task": canonical_task,
            "variant": variant,
            "prompt": prompt,
            "lyrics": lyrics,
            "instrumental": instrumental,
            "duration_seconds": duration_seconds,
            "audio_duration": duration_seconds,
            "tempo": bpm,
            "bpm": bpm,
            "key": key,
            "time_signature": time_signature,
            "seed": inputs.get("seed"),
            "audio_format": audio_format,
            "output_format": audio_format,
            "thinking": bool(inputs.get("thinking", False)),
            "prompt_expansion": bool(inputs.get("prompt_expansion", False)),
            "quality_score": bool(inputs.get("quality_score", True)),
            "batch_size": max(1, min(8, int(inputs.get("batch_size", 1)))),
        }

        if src_audio:
            params["src_audio_path"] = str(src_audio)
            params["source_audio_path"] = str(src_audio)
        if ref_audio:
            params["reference_audio_path"] = str(ref_audio)
        if canonical_task in {"music.cover", "music.audio_to_audio", "music.reference_audio"}:
            params["audio_cover_strength"] = cover_strength
            params["cover_strength"] = cover_strength
        if repainting_start is not None and repainting_end is not None:
            params["repainting_start"] = repainting_start
            params["repainting_end"] = repainting_end
        if lora_path:
            params["lora_path"] = str(lora_path)
            params["lora_weight"] = lora_weight
        if "stem_name" in inputs or "target_stem" in inputs:
            params["stem_name"] = str(inputs.get("stem_name") or inputs.get("target_stem") or "vocals").strip()
        if "add_instrument" in inputs or "layer_name" in inputs:
            params["add_instrument"] = str(inputs.get("add_instrument") or inputs.get("layer_name") or "").strip()
        if "extend_duration" in inputs:
            try:
                ext_dur = float(inputs["extend_duration"])
            except (ValueError, TypeError) as exc:
                raise InvalidRequestError(f"extend_duration must be a float, got: {inputs['extend_duration']}") from exc
            if math.isnan(ext_dur) or ext_dur <= 0.0 or ext_dur > 300.0:
                raise InvalidRequestError(f"extend_duration must be between 1.0 and 300.0, got: {ext_dur}")
            params["extend_duration"] = ext_dur

        return params

    @staticmethod
    def create_artifact_reference(*_args, **_kwargs):
        raise RuntimeError(
            "ArtifactReference must be created only after audio bytes are persisted through Factory Storage."
        )
