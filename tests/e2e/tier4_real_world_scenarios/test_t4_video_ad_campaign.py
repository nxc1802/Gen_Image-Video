"""
Tier 4 Real-World Application Scenario: Commercial Video Advertising Campaign
Validates complete video marketing pipeline:
1. Product creative brief generated by LLM
2. Keyframe 1 (Product Reveal) generated by Qwen-Image 2.1
3. Keyframe 2 (Call-to-Action) modified via Instruction Edit
4. FL2V creates motion animation transitioning between frames
5. Native Audio VAE generates synchronized commercial voiceover/soundtrack
6. Super-Resolution upscales final commercial to 4K
"""

import pytest
import httpx


@pytest.mark.tier4
class TestVideoAdCampaignWorkflow:
    def test_full_commercial_video_campaign_pipeline(self, client: httpx.Client, auth_headers):
        # Step 1: Creative Concept Brief
        brief_res = client.post("/v1/responses", headers=auth_headers, json={
            "model": "qwen-2.5-72b-instruct",
            "input": "Create a 5-second video commercial concept for an eco-friendly running shoe made from ocean plastic."
        })
        assert brief_res.status_code == 200
        concept = brief_res.json()["output"]

        # Step 2: Keyframe 1 - Product Hero Shot
        k1_res = client.post("/v1/jobs", headers=auth_headers, json={
            "service": "image",
            "model": "qwen-image-2.1",
            "task": "text_to_image",
            "inputs": {
                "prompt": f"Hero product shot of sleek futuristic running shoe on a wet coastal stone, ocean waves background. {concept}",
                "width": 1024,
                "height": 1024
            }
        })
        assert k1_res.status_code == 201
        k1_url = k1_res.json()["artifacts"][0]["url"]

        # Step 3: Keyframe 2 - CTA with Instruction Edit
        k2_res = client.post("/v1/jobs", headers=auth_headers, json={
            "service": "image",
            "model": "qwen-image-2.1",
            "task": "instruction_edit",
            "inputs": {
                "image_url": k1_url,
                "instruction": "Add a prominent glowing logo and 'Run the Ocean' typography in the center"
            }
        })
        assert k2_res.status_code == 201
        k2_url = k2_res.json()["artifacts"][0]["url"]

        # Step 4: FL2V Video Interpolation
        fl2v_res = client.post("/v1/jobs", headers=auth_headers, json={
            "service": "video",
            "model": "wan-2.2",
            "task": "fl2v",
            "inputs": {
                "first_frame_url": k1_url,
                "last_frame_url": k2_url,
                "prompt": "Camera rotates smoothly around shoe as morning sunlight breaks through sea mist",
                "fps": 24,
                "num_frames": 49
            }
        })
        assert fl2v_res.status_code == 201
        raw_video_url = fl2v_res.json()["artifacts"][0]["url"]

        # Step 5: Mux Audio VAE Stereo Track
        audio_vid_res = client.post("/v1/jobs", headers=auth_headers, json={
            "service": "video",
            "model": "wan-2.2",
            "task": "video_with_audio",
            "inputs": {
                "video_url": raw_video_url,
                "prompt": "Ocean waves crashing with modern rhythmic synth bassline",
                "enable_audio": True
            }
        })
        assert audio_vid_res.status_code == 201
        commercial_url = audio_vid_res.json()["artifacts"][0]["url"]

        # Step 6: 2x Super-Resolution for 4K Broadcast
        upscale_res = client.post("/v1/jobs", headers=auth_headers, json={
            "service": "enhancement",
            "model": "enhancement-suite-v1",
            "task": "video_super_resolution",
            "inputs": {"video_url": commercial_url, "scale_factor": 2}
        })
        assert upscale_res.status_code == 201
        final_ad = upscale_res.json()
        assert final_ad["service"] == "enhancement"
        assert len(final_ad["artifacts"]) >= 1

    def test_ad_multi_reference_character_continuity(self, client: httpx.Client, auth_headers):
        # Upload athlete face reference
        ref_res = client.post("/v1/assets/upload", headers=auth_headers, json={"mime_type": "image/png"})
        athlete_ref = ref_res.json()["s3_url"]

        # Generate character shot with reference conditioning
        char_res = client.post("/v1/jobs", headers=auth_headers, json={
            "service": "image",
            "model": "qwen-image-2.1",
            "task": "reference_conditioning",
            "inputs": {
                "prompt": "Athlete tying shoes at coastal marathon starting line",
                "reference_image_urls": [athlete_ref]
            }
        })
        assert char_res.status_code == 201
        assert len(char_res.json()["artifacts"]) >= 1

    def test_ad_frame_interpolation_to_60fps(self, client: httpx.Client, auth_headers):
        # Smooth motion video using RIFE
        rife_res = client.post("/v1/jobs", headers=auth_headers, json={
            "service": "enhancement",
            "model": "enhancement-suite-v1",
            "task": "frame_interpolation",
            "inputs": {
                "video_url": "https://s3.ai.example.com/assets/24fps_ad.mp4",
                "target_fps": 60,
                "multiplier": 2
            }
        })
        assert rife_res.status_code == 201
        assert rife_res.json()["state"] == "QUEUED"

    def test_commercial_video_with_audio_alignment(self, client: httpx.Client, auth_headers):
        # Align commercial voiceover with transcript
        align_res = client.post("/v1/audio/alignments", headers=auth_headers, json={
            "audio_url": "https://s3.ai.example.com/assets/ad_voiceover.wav",
            "transcript_text": "Run the ocean. Experience the future of sustainable motion."
        })
        assert align_res.status_code == 200
        assert len(align_res.json()["aligned_words"]) >= 2
